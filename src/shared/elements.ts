export type Align = "left" | "center" | "right";
export interface Slide {
	title: string;
	subtitle: string;
	image: string;
	// Added later: slides saved before these existed do not have them.
	/** Seconds on screen; 0 = the slideshow's. */
	seconds?: number;
	/** Empty = the slideshow's. */
	position?: "" | "bottom" | "center" | "top";
	/** Text colour; empty = the slideshow's. */
	color?: string;
	/** Shown as a small QR code. */
	link?: string;
}
