/**
 * The element catalogue: every element type with its default properties and
 * the form fields the editor shows for it. Adding an element means adding an
 * entry here, a renderer in `src/client/display/elements/`, and (when it needs
 * server data) a resolver in `src/server/data/`.
 */
import type { AnyEl, ElementCommon } from "./types";

export type FieldKind =
	| "text"
	| "textarea"
	| "number"
	| "range"
	| "select"
	| "toggle"
	| "color"
	| "media"
	| "album"
	| "entity"
	| "datetime"
	| "time"
	| "days"
	| "list";

export interface Field {
	key: string;
	label: string;
	kind: FieldKind;
	/** Advanced fields are folded away until asked for. */
	advanced?: boolean;
	/** Only the server may know the value (an API key, a token): it is blanked in what a screen receives. */
	secret?: boolean;
	help?: string;
	placeholder?: string;
	options?: { value: string; label: string }[];
	min?: number;
	max?: number;
	step?: number;
	unit?: string;
	/** `media` fields: which files can be picked. */
	media?: "image" | "video" | "document" | "any";
	/** `entity` fields: restrict the picker to these Home Assistant domains. */
	domains?: string[];
	/** `list` fields: the fields of one row, and how a new row starts. */
	fields?: Field[];
	item?: Record<string, unknown>;
	itemLabel?: string;
	/** Only show the field when this returns true. */
	when?: (el: Record<string, unknown>) => boolean;
}

export type Category = "layout" | "content" | "time" | "info" | "ha" | "mqtt";

