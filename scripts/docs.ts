/**
 * `bun run docs`: writes `docs/elements.md` from the element catalogue, so
 * the reference always matches what the editor offers.
 */
import { join } from "node:path";
import { CATEGORIES, COMMON_FIELDS, ELEMENT_TYPES, ELEMENTS, type Field } from "../src/shared/elements";

/** Table-cell text: Markdown characters in it are meant literally. */
const cell = (text: string | undefined) => (text ?? "").replace(/([|*[\]])/g, "\\$1").replace(/\n/g, " ");
/** The anchor GitHub gives a heading. */
const anchor = (heading: string) =>
	heading
		.toLowerCase()
		.replace(/[^a-z0-9 -]/g, "")
		.replace(/ /g, "-");

function describe(field: Field): string {
	const parts: string[] = [];
	if (field.help) parts.push(field.help);
	if (field.kind === "select" && field.options) parts.push(`Choices: ${field.options.map((o) => o.label).join(", ")}.`);
	if (field.kind === "list" && field.fields)
		parts.push(`Each row has: ${field.fields.map((f) => f.label.toLowerCase()).join(", ")}.`);
	if (field.kind === "entity")
		parts.push(field.domains ? `A Home Assistant entity (${field.domains.join(", ")}).` : "A Home Assistant entity.");
	if ((field.kind === "range" || field.kind === "number") && field.min !== undefined && field.max !== undefined)
		parts.push(`${field.min} to ${field.max}${field.unit ? ` ${field.unit}` : ""}.`);
	return parts.join(" ");
}

function table(fields: Field[]): string[] {
	if (!fields.length) return ["_No options._", ""];
	return [
		"| Option | | What it does |",
		"| --- | --- | --- |",
		...fields.map((f) => `| ${cell(f.label)} | ${f.advanced ? "advanced" : ""} | ${cell(describe(f))} |`),
		"",
	];
}

const lines: string[] = [
	"# Elements",
	"",
	"<!-- Generated by `bun run docs` from src/shared/elements.ts. Do not edit by hand. -->",
	"",
	`SideDisplay has ${ELEMENT_TYPES.length} elements. Each one shows its everyday options first; the ones marked _advanced_ are folded under **Advanced** in the editor.`,
	"",
	...CATEGORIES.map(
		(c) =>
			`- [${c.label}](#${anchor(c.label)}): ${ELEMENT_TYPES.filter((t) => ELEMENTS[t].category === c.id)
				.map((t) => ELEMENTS[t].label)
				.join(", ")}`,
	),
	"- [Options every element has](#options-every-element-has)",
	"",
];

for (const category of CATEGORIES) {
	lines.push(`## ${category.label}`, "");
	for (const type of ELEMENT_TYPES.filter((t) => ELEMENTS[t].category === category.id)) {
		const d = ELEMENTS[type];
		lines.push(`### ${d.label}`, "", d.description, "");
		if ("data" in d && d.data)
			lines.push(
				`Refreshed by the server every ${d.data >= 120 ? `${Math.round(d.data / 60)} minutes` : `${d.data} seconds`}${category.id === "ha" ? ", and at once when the entity changes" : category.id === "mqtt" ? ", and at once when a message arrives" : ""}.`,
				"",
			);
		lines.push(...table(d.fields));
	}
}

lines.push(
	"## Options every element has",
	"",
	"Under **Placement & style** in the editor.",
	"",
	...table(COMMON_FIELDS),
	"### Free placement",
	"",
	"Set **Placement** to _Free_ and the element leaves the layout flow: drag it anywhere in the preview, resize it with the round handle at its corner, nudge it with the arrow keys (Shift for bigger steps) and rotate it from the options. Free elements are drawn above the layout, in the order of the element list.",
	"",
);

await Bun.write(join(import.meta.dir, "../docs/elements.md"), lines.join("\n"));
console.log(`docs/elements.md written (${ELEMENT_TYPES.length} elements)`);
